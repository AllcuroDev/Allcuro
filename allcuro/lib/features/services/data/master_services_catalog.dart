import 'package:flutter/material.dart';

class MasterServiceItem {
  final String id;
  final String name;
  final String mainCategory;

  /// Other categories this service is also listed under, e.g. ['Caregivers'].
  final List<String> alsoIn;
  final String subcategory;
  final String description;
  final String includes;
  final String notIncluded;
  final String duration;
  final String professional;
  final String price;
  final String notes;
  final IconData icon;

  /// Care-icon key shared with the web and Supabase (`services.icon`), e.g.
  /// 'bath'. Empty for bundled entries, which resolve icons by [id].
  final String iconKey;

  /// Supabase Storage artwork uploaded from the admin; overrides the icon when set.
  final String? imageUrl;
  final String badge;

  const MasterServiceItem({
    required this.id,
    required this.name,
    required this.mainCategory,
    this.alsoIn = const [],
    required this.subcategory,
    required this.description,
    required this.includes,
    required this.notIncluded,
    required this.duration,
    required this.professional,
    required this.price,
    required this.notes,
    required this.icon,
    this.iconKey = '',
    this.imageUrl,
    this.badge = '',
  });
}

